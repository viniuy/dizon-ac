// Mirrors the existing public.tickets schema in the dizon-ac Supabase project

export type TicketStatus =
  | 'pending_confirmation' | 'confirmed' | 'completed' | 'awaiting_payment'
  | 'paid' | 'disputed' | 'cancelled' | 'backjob'

export type TicketSource = 'web' | 'facebook' | 'call' | 'chat'

export const SOURCE_LABEL: Record<TicketSource, string> = {
  web: 'Website',
  facebook: 'Facebook',
  call: 'Phone call',
  chat: 'Chat',
}

/** Sources staff can pick when adding a ticket by hand */
export const MANUAL_SOURCES: TicketSource[] = ['facebook', 'call', 'chat']

export type CancellationReason = 'customer_request' | 'staff_decision' | 'no_show' | 'technician_unavailable'

export interface Ticket {
  id: string
  ticket_ref: string
  source: TicketSource
  is_guest: boolean
  contact_name: string
  contact_number: string
  /** e.g. the customer's Messenger conversation */
  contact_link: string | null
  /** Generated by the database: last 10 digits of the number, for matching returning customers */
  phone_key: string
  address: string
  map_url: string | null
  service_type: string
  unit_details: string | null
  problem_description: string | null
  preferred_date: string | null
  /** Philippine local date/times: "YYYY-MM-DD" and "HH:MM:SS" */
  scheduled_date: string | null
  scheduled_start: string | null
  scheduled_end: string | null
  status: TicketStatus
  cancelled_reason: CancellationReason | null
  calendar_event_id: string | null
  staff_notes: string | null
  /** Return visit for an earlier job (parent_ticket_id) */
  is_backjob: boolean
  is_warranty_backjob: boolean
  parent_ticket_id: string | null
  payment_status: 'unpaid' | 'paid' | 'waived' | 'disputed'
  /** Call the customer about rebooking on or after this date ("YYYY-MM-DD") */
  follow_up_date: string | null
  /** When staff handled the follow-up call */
  follow_up_done_at: string | null
  /** 7 (cleaning) or 90 (repair) days of warranty, null for none */
  warranty_days: WarrantyDays | null
  /** Last covered day ("YYYY-MM-DD") */
  warranty_until: string | null
  completed_at: string | null
  created_at: string
  updated_at: string
}

/** Another job already on a date, used for availability and clash checks */
export type DayBooking = Pick<Ticket, 'id' | 'ticket_ref' | 'status' | 'contact_name' | 'service_type' | 'address' | 'scheduled_start' | 'scheduled_end'>

