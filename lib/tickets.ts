/*
  Scheduling capacity: one crew, one job at a time, during working hours (minutes
  since midnight). A day's free time is these hours minus what's already booked.
*/
export const WORK_START = 7 * 60
export const WORK_END = 19 * 60

/** No jobs on Sundays (0 = Sunday, as in Date.getDay) */
export const CLOSED_WEEKDAYS = [0]
/** Is this "YYYY-MM-DD" a day the crew doesn't work? */
export const isClosedDay = (date: string) => CLOSED_WEEKDAYS.includes(new Date(`${date}T00:00:00Z`).getUTCDay())

/** All scheduling happens in Philippine time */
export const TIME_ZONE = 'Asia/Manila'

const fmt = (opts: Intl.DateTimeFormatOptions) =>
  new Intl.DateTimeFormat('en-PH', { timeZone: TIME_ZONE, ...opts })

export const formatDateTime = (iso: string) =>
  fmt({ weekday: 'short', month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' }).format(new Date(iso))

export const formatDate = (isoDate: string) =>
  fmt({ weekday: 'short', month: 'short', day: 'numeric', year: 'numeric' }).format(new Date(`${isoDate}T00:00:00+08:00`))

/** "HH:MM[:SS]" → "9:00 AM" */
export const formatTime = (time: string) =>
  fmt({ hour: 'numeric', minute: '2-digit' }).format(new Date(`2000-01-01T${time.slice(0, 5)}:00+08:00`))
